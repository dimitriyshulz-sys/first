def names_set(text):
    """Слова с заглавной буквой не в начале предложения — считаем собственными именами."""
    ns = set()
    for m in re.finditer(r'(?<=[а-яё,;:] )([А-ЯЁ][а-яё]+)', text):
        ns.add(m.group(1))
    return ns

def caps_to_normal(text, names):
    def repl_run(m):
        run = m.group(0)
        start = m.start()
        before = text[max(0, start - 3):start]
        words = re.split(r'(\W+)', run)
        out = []
        for w in words:
            if re.fullmatch(r'[А-ЯЁ][А-ЯЁ-]*[А-ЯЁ]|[А-ЯЁ]', w or '') and len(w) > 1:
                if w in CAPS_ABBR:
                    out.append(CAPS_ABBR[w]); continue
                lw = w.lower()
                t = lw[:1].upper() + lw[1:]
                out.append(t if t in names else lw)
            else:
                out.append(w)
        res = ''.join(out)
        res = re.sub(r'([.!?]\s+)([а-яё])', lambda k: k.group(1) + k.group(2).upper(), res)
        if start == 0 or re.search(r'(^|\n|[.!?…]\s|«|\n— |^— )$', before):
            res = cap(res)
        return res
    return re.sub(r'\b[А-ЯЁ][А-ЯЁ-]*[А-ЯЁ]\b(?:[ ,.!?—-]+\b[А-ЯЁ][А-ЯЁ-]*[А-ЯЁ]\b)*', repl_run, text)

def sentence_case(s):
    s = s.strip()
    s = re.sub(r'(^|[.!?…]\s+(?:— )?)(«?)([а-яё])', lambda m: m.group(1) + m.group(2) + m.group(3).upper(), s)
    return s

def visions(text):
    def repl(m):
        body = m.group(1)
        long_v = len(body) >= 60 and re.search(r'[.!?]', body)
        short_v = len(body) >= 15 and (re.search(r'\. ', body) or body.endswith('…'))
        if not (long_v or short_v):
            return m.group(0)
        body = sentence_case(body.replace(' — ', ' — '))
        if not re.search(r'[.!?…]$', body): body += '…'
        return f'{VISION_OPEN} {body} {PAUSE}'
    return re.sub(r'\(((?:[а-яёА-ЯЁ…«])[^()]*)\)', repl, text)

def strip_md(text):
    text = re.sub(r'(?m)^#\s+(.+)$', lambda m: f'{LPAUSE}\n\n{sentence_case(m.group(1).strip().lower())}.\n\n{LPAUSE}', text)
    def chap(m):
        n = int(m.group(1)); title = m.group(2).strip()
        return f'Глава {ordinal(n, "nomn")[:-2]}ая. {title}.\n\n{PAUSE}' if False else f'Глава {chapter_word(n)}. {title}.\n\n{PAUSE}'
    text = re.sub(r'(?m)^##\s+(\d+)\.\s+(.+)$', chap, text)
    text = re.sub(r'(?m)^---\s*$', LPAUSE, text)
    text = re.sub(r'(?m)^(?:>[ \t]?)+', '', text)
    text = text.replace('**', '').replace('*', '')
    text = re.sub(r'(?m)^[┌└].*$', '', text)
    text = re.sub(r'[│]', '', text)
    text = re.sub(r'\.\.+(?=»)', '.', text)
    text = re.sub(r'([.!?…])\.(\s)', r'\1\2', text)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text

def chapter_word(n):
    w = ordinal(n, 'nom')
    # женский род: «глава первая»
    w = re.sub(r'(ый|ой)$', 'ая', w).replace('третий', 'третья')
    return w

def apply_stress(text):
    for a, b in STRESS_MANUAL:
        text = text.replace(a, b)
    for pat, rep in STRESS:
        text = re.sub(pat, rep, text)
    return text

def convert(raw, names):
    t = raw
    for a, b in MANUAL:
        t = t.replace(a, b)
    # таблица гл. 19
    t = re.sub(r'(?ms)^\| Жертва.*?^\| А\. Полякова[^\n]*\n', TABLE_PROSE + '\n', t)
    # даты: письма-заголовки в именительном
    t = re.sub(r'(Кинешма|Старая Пряжа|Сургут), (\d{1,2}) (' + MONTHS + r') (\d{4}) г\.',
               lambda m: f'{m.group(1)}, {dmy(int(m.group(2)), MNAMES.index(m.group(3)) + 1, int(m.group(4)), "nom")}.', t)
    # даты с годом — родительный
    t = re.sub(r'(\d{1,2}) (' + MONTHS + r') (\d{4}) (года|г\.)(?!,)',
               lambda m: dmy(int(m.group(1)), MNAMES.index(m.group(2)) + 1, int(m.group(3))) + ('.' if m.group(4) == 'г.' else ''), t)
    t = re.sub(r'(\d{1,2}) (' + MONTHS + r') (\d{4}) (?:года|г\.)',
               lambda m: dmy(int(m.group(1)), MNAMES.index(m.group(2)) + 1, int(m.group(3))), t)
    t = re.sub(r'(\d{1,2}) (' + MONTHS + r')', lambda m: dmy(int(m.group(1)), MNAMES.index(m.group(2)) + 1), t)
    t = re.sub(r'\bв (\d{4}) году', lambda m: 'в ' + year(int(m.group(1)), 'prep') + ' году', t)
    t = re.sub(r'(\d{4}) г\. р\.(?=\*?\s+[А-ЯЁ])', lambda m: year(int(m.group(1)), 'gen') + ' года рождения.', t)
    t = re.sub(r'(\d{4}) г\. р\.', lambda m: year(int(m.group(1)), 'gen') + ' года рождения', t)
    t = re.sub(r'\b(с|до|Летом|выборы|от) (\d{4}) года', lambda m: m.group(1) + ' ' + year(int(m.group(2)), 'gen') + ' года', t)
    t = re.sub(r'(\d{4}) год\b', lambda m: year(int(m.group(1)), 'nom') + ' год', t)
    t = re.sub(r'\b(\d+) (лет|года|год)\b', lambda m: card(int(m.group(1))) + ' ' + m.group(2), t)
    # ремарки стенограмм
    def rem(m):
        k = m.group(1).strip()
        if k in REMARKS: return REMARKS[k]
        return m.group(1)  # авторские ремарки к сюжету ТВ — читаем
    t = re.sub(r'\(\*([^)]*?)\*\)', rem, t)
    for a, b in SPECIAL:
        t = t.replace(a, b)
    for a, b in INITIALS:
        t = t.replace(a, b)
    for a, b in ABBR:
        if a.endswith('.') and not b.endswith('.'):
            # сокращение в конце предложения: точку сохраняем
            t = re.sub(re.escape(a) + r'(?=\*?\s+[А-ЯЁ«(])', b + '.', t)
        t = t.replace(a, b)
    t = caps_to_normal(t, names)
    t = visions(t)
    t = strip_md(t)
    t = apply_stress(t)
    return t.strip() + '\n'

def split_parts(text, limit=LIMIT):
    paras = text.split('\n\n'); parts = []; cur = ''
    for p in paras:
        if len(cur) + len(p) + 2 > limit and cur:
            parts.append(cur.strip()); cur = ''
        cur += p + '\n\n'
    if cur.strip(): parts.append(cur.strip())
    return parts

