def card(n, fem=False):
    if n == 0: return 'ноль'
    parts = []
    if n >= 1000:
        t = n // 1000; n %= 1000
        tw = card(t, fem=True)
        if t % 10 == 1 and t % 100 != 11: parts.append(tw + ' тысяча')
        elif t % 10 in (2, 3, 4) and t % 100 not in (12, 13, 14): parts.append(tw + ' тысячи')
        else: parts.append(tw + ' тысяч')
        if t == 1: parts[-1] = 'тысяча'
    if n >= 100: parts.append(HUNDREDS[n // 100]); n %= 100
    if n >= 20: parts.append(TENS[n // 10]); n %= 10
    if n > 0:
        w = UNITS[n]
        if fem and n == 1: w = 'одна'
        if fem and n == 2: w = 'две'
        parts.append(w)
    return ' '.join(parts)

ORD_STEM = {1:'перв',2:'втор',3:'трет',4:'четвёрт',5:'пят',6:'шест',7:'седьм',8:'восьм',9:'девят',
            10:'десят',11:'одиннадцат',12:'двенадцат',13:'тринадцат',14:'четырнадцат',15:'пятнадцат',
            16:'шестнадцат',17:'семнадцат',18:'восемнадцат',19:'девятнадцат',20:'двадцат',30:'тридцат',
            40:'сороков',50:'пятидесят',60:'шестидесят',70:'семидесят',80:'восьмидесят',90:'девяност'}

def _ord_word(n, case):
    st = ORD_STEM[n]
    if n == 3:
        return {'gen':'третьего','prep':'третьем','nom':'третий','nomn':'третье'}[case]
    stressed_end = n in (2, 6, 7, 8, 40)
    end = {'gen':'ого','prep':'ом','nom':'ой' if stressed_end else 'ый','nomn':'ое'}[case]
    return st + end

def ordinal(n, case):
    """Порядковое числительное 1..99 (case: gen, prep, nom — м. р., nomn — ср. р.)."""
    if n < 20 or n % 10 == 0:
        return _ord_word(n, case)
    return TENS[n // 10] + ' ' + _ord_word(n % 10, case)

def year(y, case):
    if y == 2000:
        return {'gen':'двухтысячного','prep':'двухтысячном','nom':'двухтысячный','nomn':'двухтысячное'}[case]
    head = 'тысяча девятьсот' if y < 2000 else 'две тысячи'
    return head + ' ' + ordinal(y % 100, case)

MONTHS = 'января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря'
MNAMES = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря']

def dmy(d, m, y=None, case='gen', short=False):
    s = ordinal(d, 'nomn' if case == 'nom' else 'gen') + ' ' + MNAMES[m - 1]
    if y:
        s += ' ' + (ordinal(y % 100, 'gen') if short else year(y, 'gen'))
        if not short: s += ' года'
    return s

def cap(s): return s[:1].upper() + s[1:]

